public class ConversaoDeUnidadesDeVolume {

    public static double litroParaCm3(double litros) {
        return litros * 1000;
    }

    public static double metro3ParaLitros(double metros3) {
        return metros3 * 1000;
    }

    public static double metro3ParaPes3(double metros3) {
        return metros3 * 35.32;
    }

    public static double galaoParaPolegadas3(double galoes) {
        return galoes * 231;
    }

    public static double galaoParaLitros(double galoes) {
        return galoes * 3.785;
    }
}
